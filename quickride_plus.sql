DROP DATABASE IF EXISTS quickride_plus;
CREATE DATABASE quickride_plus;
USE quickride_plus;

CREATE TABLE riders (
  rider_id    INT PRIMARY KEY,
  rider_name  VARCHAR(50) NOT NULL,
  city        VARCHAR(30) NOT NULL,
  plan        VARCHAR(10) NOT NULL,
  signup_date DATE        NOT NULL
) ENGINE=InnoDB;

CREATE TABLE drivers (
  driver_id    INT PRIMARY KEY,
  driver_name  VARCHAR(50) NOT NULL,
  home_city    VARCHAR(30) NOT NULL,
  vehicle_type VARCHAR(20) NOT NULL,
  join_date    DATE        NOT NULL
) ENGINE=InnoDB;

CREATE TABLE trips (
  trip_id        INT PRIMARY KEY,
  rider_id       INT NOT NULL,
  driver_id      INT NOT NULL,
  city           VARCHAR(30)  NOT NULL,
  trip_date      DATE         NOT NULL,
  distance_km    DECIMAL(5,1) NOT NULL,
  duration_min   INT          NOT NULL,
  fare           DECIMAL(8,2) NOT NULL,
  payment_method VARCHAR(20)  NOT NULL,
  rating         DECIMAL(2,1),
  status         VARCHAR(20)  NOT NULL,
  CONSTRAINT fk_rider  FOREIGN KEY (rider_id)  REFERENCES riders(rider_id),
  CONSTRAINT fk_driver FOREIGN KEY (driver_id) REFERENCES drivers(driver_id)
) ENGINE=InnoDB;

